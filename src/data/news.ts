export function getNewsBySlug(slug: string) {
  return news.find((item) => item.slug === slug);
}

export function getUrgentNews() {
  return news.filter((item) => item.urgent).sort((a, b) => b.date.localeCompare(a.date))[0];
}

export function getLatestNews(limit = 3) {
  return [...news]
    .filter((item) => item.type === "news" || item.type === "announcement")
    .sort((a, b) => b.date.localeCompare(a.date))
    .slice(0, limit);
}

export function getAnnouncements(limit = 3) {
  return [...news]
    .filter((item) => item.type === "announcement" && !item.urgent)
    .sort((a, b) => b.date.localeCompare(a.date))
    .slice(0, limit);
}

export function getEvents(limit = 6) {
  return [...news]
    .filter((item) => item.type === "event")
    .sort((a, b) => b.date.localeCompare(a.date))
    .slice(0, limit);
}
